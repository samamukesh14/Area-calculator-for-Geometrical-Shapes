# area of a trapezoid
# area = (((a + b) * Height) / 2)

a = int(input("enter the first parallel side of trapezoid:"))
b = int(input("enter the second parallel side of trapezoid:"))
Height = int(input("enter the height of trapezoid:"))
Area = (a + b) * Height/2

print("The area of trapezoid ", Area, "sq")
